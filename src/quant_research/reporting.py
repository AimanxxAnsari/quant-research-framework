"""Write generated results into README sections delimited by markers."""

from __future__ import annotations

from pathlib import Path
from typing import cast

import pandas as pd

from quant_research.errors import ConfigError


def markers(name: str) -> tuple[str, str]:
    return f"<!-- {name}:START -->", f"<!-- {name}:END -->"


def inject(readme: str, name: str, block: str) -> str:
    start, end = markers(name)
    if start not in readme or end not in readme:
        raise ConfigError(f"README is missing the {start} / {end} markers")
    head, rest = readme.split(start, 1)
    _, tail = rest.split(end, 1)
    note = "<!-- Generated by `qrf study`. Do not edit by hand. -->"
    return f"{head}{start}\n{note}\n\n{block.strip()}\n\n{end}{tail}"


def inject_file(path: Path, name: str, block: str) -> None:
    path.write_text(inject(path.read_text(), name, block))


def _escape(text: str) -> str:
    return text.replace("|", "\\|")  # a bare pipe would start a new column


def md_table(df: pd.DataFrame, floatfmt: str | dict[str, str] = "{:.3f}") -> str:
    """Minimal Markdown table. ``floatfmt`` is one format or a dict column -> format."""
    cols = [str(c) for c in df.columns]
    lines = [
        "| " + " | ".join([str(df.index.name or ""), *cols]) + " |",
        "|" + "---|" * (len(cols) + 1),
    ]
    for idx, row in df.iterrows():
        cells = []
        for c, v in zip(df.columns, row, strict=True):
            fmt = floatfmt.get(c, "{:.3f}") if isinstance(floatfmt, dict) else floatfmt
            cells.append(fmt.format(v) if isinstance(v, float) else _escape(str(v)))
        lines.append("| " + " | ".join([_escape(str(idx)), *cells]) + " |")
    return "\n".join(lines)


def cell(df: pd.DataFrame, row: str, col: str) -> float:
    """One numeric cell of a results table, for use in generated commentary."""
    return float(cast(float, df.loc[row, col]))
